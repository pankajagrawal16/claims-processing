# get-keys.ps1
# Create the repository-root .env file from a deployed Claims MicroHack lab.
# PowerShell counterpart of get-keys.sh; it writes the same .env file.

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [Alias('g')]
    [string]$ResourceGroup
)

$ErrorActionPreference = 'Stop'

$scriptDirectory = Split-Path -Parent $MyInvocation.MyCommand.Definition
$repoRoot = Split-Path -Parent $scriptDirectory
$envFile = Join-Path $repoRoot '.env'
$onWindows = [System.Environment]::OSVersion.Platform -eq 'Win32NT'

function Invoke-AzText {
    # Runs az and returns its trimmed output, or an empty string when az fails.
    param([Parameter(Mandatory = $true)][string[]]$Arguments)

    $output = & az @Arguments 2>$null
    if ($LASTEXITCODE -ne 0) {
        return ''
    }
    return (($output | Out-String).Trim())
}

function Invoke-AzLines {
    # Runs az and returns each non-empty output line.
    param([Parameter(Mandatory = $true)][string[]]$Arguments)

    $output = & az @Arguments 2>$null
    if ($LASTEXITCODE -ne 0) {
        return @()
    }
    return @($output | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | ForEach-Object { $_.Trim() })
}

function Assert-Value {
    param([string]$Value, [string]$Name)

    if ([string]::IsNullOrWhiteSpace($Value)) {
        throw "Could not retrieve $Name. Confirm the lab deployment succeeded and your account has access."
    }
}

function Get-DeploymentOutput {
    param([string]$DeploymentName, [string]$OutputName)

    if ([string]::IsNullOrEmpty($DeploymentName)) {
        return ''
    }
    return Invoke-AzText @(
        'deployment', 'group', 'show',
        '--resource-group', $ResourceGroup,
        '--name', $DeploymentName,
        '--query', "properties.outputs.$OutputName.value",
        '--output', 'tsv'
    )
}

function Find-LabDeployment {
    # Returns the newest successful deployment that publishes the Foundry project endpoint.
    $names = Invoke-AzLines @(
        'deployment', 'group', 'list',
        '--resource-group', $ResourceGroup,
        '--query', "reverse(sort_by([?properties.provisioningState=='Succeeded'], &properties.timestamp))[].name",
        '--output', 'tsv'
    )
    foreach ($name in $names) {
        if (Get-DeploymentOutput $name 'aiFoundryProjectEndpoint') {
            return $name
        }
    }
    return ''
}

function Get-ResourceName {
    param([string]$ResourceType, [string]$NameFilter = '')

    $query = '[0].name'
    if ($NameFilter) {
        $query = "[?contains(name, '$NameFilter')].name | [0]"
    }
    return Invoke-AzText @(
        'resource', 'list',
        '--resource-group', $ResourceGroup,
        '--resource-type', $ResourceType,
        '--query', $query,
        '--output', 'tsv'
    )
}

function Set-OwnerOnlyPermissions {
    param([string]$Path)

    if ($onWindows) {
        & icacls $Path /inheritance:r /grant:r "$($env:USERNAME):F" | Out-Null
        if ($LASTEXITCODE -ne 0) {
            throw "Could not restrict permissions on $Path."
        }
    }
    else {
        & chmod 600 $Path
        if ($LASTEXITCODE -ne 0) {
            throw "Could not restrict permissions on $Path."
        }
    }
}

function Write-EnvFile {
    param(
        [string]$ProjectEndpoint,
        [string]$FoundryEndpoint,
        [string]$FoundryKey,
        [string]$SearchEndpoint,
        [string]$SearchKey,
        [string]$SearchIndexName,
        [string]$PoliciesContainerName,
        [string]$StorageConnectionString
    )

    $lines = @(
        '# Generated by labautomation/get-keys.ps1. Do not commit this file.',
        '',
        '# Microsoft Foundry project and models',
        "AI_FOUNDRY_PROJECT_ENDPOINT=$ProjectEndpoint",
        "FOUNDRY_PROJECT_ENDPOINT=$ProjectEndpoint",
        'MODEL_DEPLOYMENT_NAME=gpt-5.4',
        'FOUNDRY_MODEL=gpt-5.4',
        'FOUNDRY_QUARANTINE_MODEL=gpt-5.4',
        '',
        '# Mistral Document AI',
        "MISTRAL_DOCUMENT_AI_ENDPOINT=$FoundryEndpoint",
        "MISTRAL_DOCUMENT_AI_KEY=$FoundryKey",
        'MISTRAL_DOCUMENT_AI_DEPLOYMENT_NAME=mistral-document-ai-2512',
        'MISTRAL_DOCUMENT_AI_API_VERSION=2024-05-01-preview',
        '',
        '# Azure AI Search and Foundry IQ',
        "FOUNDRY_IQ_SEARCH_ENDPOINT=$SearchEndpoint",
        "FOUNDRY_IQ_SEARCH_KEY=$SearchKey",
        "FOUNDRY_IQ_SEARCH_INDEX_NAME=$SearchIndexName",
        'FOUNDRY_IQ_KNOWLEDGE_SOURCE_NAME=crash-statements-ks',
        'FOUNDRY_IQ_KNOWLEDGE_BASE_NAME=crash-statements-kb',
        "SEARCH_SERVICE_ENDPOINT=$SearchEndpoint",
        "SEARCH_ADMIN_KEY=$SearchKey",
        '',
        '# Azure Storage policy documents',
        "AZURE_STORAGE_CONNECTION_STRING=$StorageConnectionString",
        "AZURE_POLICIES_CONTAINER_NAME=$PoliciesContainerName",
        '',
        '# Sequential workflow',
        'HUMAN_REVIEW_CONFIDENCE_THRESHOLD=0.9'
    )

    $temporaryFile = "$envFile.tmp.$([guid]::NewGuid().ToString('N'))"
    try {
        $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
        [System.IO.File]::WriteAllText($temporaryFile, (($lines -join "`n") + "`n"), $utf8NoBom)
        Set-OwnerOnlyPermissions $temporaryFile
        Move-Item -Path $temporaryFile -Destination $envFile -Force
    }
    finally {
        if (Test-Path $temporaryFile) {
            Remove-Item $temporaryFile -Force
        }
    }
}

if (-not (Get-Command az -ErrorAction SilentlyContinue)) {
    throw 'Azure CLI is required but was not found.'
}

& az account get-access-token --output none 2>$null
if ($LASTEXITCODE -ne 0) {
    Write-Host 'Sign in with the assigned lab account.'
    & az login --use-device-code
    if ($LASTEXITCODE -ne 0) {
        throw 'Azure sign-in failed.'
    }
}

& az group show --name $ResourceGroup --output none
if ($LASTEXITCODE -ne 0) {
    throw "Resource group '$ResourceGroup' was not found or is not accessible."
}

Write-Host 'Locating the Claims MicroHack deployment...'
$deploymentName = Find-LabDeployment

$storageAccountName = Get-DeploymentOutput $deploymentName 'storageAccountName'
$policiesContainerName = Get-DeploymentOutput $deploymentName 'policiesContainerName'
$searchServiceName = Get-DeploymentOutput $deploymentName 'searchServiceName'
$searchIndexName = Get-DeploymentOutput $deploymentName 'searchIndexName'
$aiFoundryName = Get-DeploymentOutput $deploymentName 'aiFoundryHubName'
$aiFoundryProjectEndpoint = Get-DeploymentOutput $deploymentName 'aiFoundryProjectEndpoint'

if (-not $storageAccountName) {
    $storageAccountName = Get-ResourceName 'Microsoft.Storage/storageAccounts'
}
if (-not $searchServiceName) {
    $searchServiceName = Get-ResourceName 'Microsoft.Search/searchServices'
}
if (-not $aiFoundryName) {
    $aiFoundryName = Get-ResourceName 'Microsoft.CognitiveServices/accounts' 'aifoundry'
}
if (-not $policiesContainerName) {
    $policiesContainerName = 'policies'
}
if (-not $searchIndexName) {
    $searchIndexName = 'crash-statements'
}
if (-not $aiFoundryProjectEndpoint) {
    $projectName = Get-DeploymentOutput $deploymentName 'aiFoundryProjectName'
    if (-not $projectName) {
        $projectResource = Get-ResourceName 'Microsoft.CognitiveServices/accounts/projects'
        $projectName = $projectResource
        if ($projectResource.Contains('/')) {
            $projectName = $projectResource.Substring($projectResource.IndexOf('/') + 1)
        }
    }
    if (-not $projectName -and $aiFoundryName -like '*-aifoundry-*') {
        $projectName = [regex]::Replace($aiFoundryName, '-aifoundry-', '-aiproject-', 1)
    }
    if ($aiFoundryName -and $projectName) {
        $aiFoundryProjectEndpoint = "https://$aiFoundryName.services.ai.azure.com/api/projects/$projectName"
    }
}

Assert-Value $storageAccountName 'storage account name'
Assert-Value $policiesContainerName 'policies container name'
Assert-Value $searchServiceName 'Search service name'
Assert-Value $searchIndexName 'Search index name'
Assert-Value $aiFoundryName 'Foundry account name'
Assert-Value $aiFoundryProjectEndpoint 'Foundry project endpoint'

$searchEndpoint = "https://$searchServiceName.search.windows.net"
$aiFoundryEndpoint = "https://$aiFoundryName.cognitiveservices.azure.com"

Write-Host 'Retrieving credentials from the deployed resources...'
$storageConnectionString = Invoke-AzText @(
    'storage', 'account', 'show-connection-string',
    '--resource-group', $ResourceGroup,
    '--name', $storageAccountName,
    '--query', 'connectionString',
    '--output', 'tsv'
)
$searchKey = Invoke-AzText @(
    'search', 'admin-key', 'show',
    '--resource-group', $ResourceGroup,
    '--service-name', $searchServiceName,
    '--query', 'primaryKey',
    '--output', 'tsv'
)
$foundryKey = Invoke-AzText @(
    'cognitiveservices', 'account', 'keys', 'list',
    '--resource-group', $ResourceGroup,
    '--name', $aiFoundryName,
    '--query', 'key1',
    '--output', 'tsv'
)

Assert-Value $storageConnectionString 'storage connection string'
Assert-Value $searchKey 'Search admin key'
Assert-Value $foundryKey 'Foundry API key'

Write-EnvFile `
    -ProjectEndpoint $aiFoundryProjectEndpoint `
    -FoundryEndpoint $aiFoundryEndpoint `
    -FoundryKey $foundryKey `
    -SearchEndpoint $searchEndpoint `
    -SearchKey $searchKey `
    -SearchIndexName $searchIndexName `
    -PoliciesContainerName $policiesContainerName `
    -StorageConnectionString $storageConnectionString

Write-Host "Created $envFile with owner-only permissions."
if ($deploymentName) {
    Write-Host "Deployment: $deploymentName"
}
else {
    Write-Host 'Deployment metadata unavailable; resources discovered from the group.'
}
Write-Host "Foundry account: $aiFoundryName"
Write-Host "Search service: $searchServiceName"
Write-Host "Storage account: $storageAccountName"
Write-Host 'Secret values were not displayed.'
